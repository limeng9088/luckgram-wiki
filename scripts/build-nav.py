#!/usr/bin/env python3
"""Turn SUMMARY.md and en/SUMMARY.md into the sidebar includes used by _layouts/default.html.

Run after editing either SUMMARY.md:  python3 scripts/build-nav.py
"""
import html
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ITEM = re.compile(r"^(\s*)\* \[(.+?)\]\((.+?)\)\s*$")


def url(prefix, target):
    path, _, frag = target.partition("#")
    path = re.sub(r"(^|/)README\.md$", r"\1", path)
    path = re.sub(r"\.md$", ".html", path)
    return prefix + path + ("#" + frag if frag else "")


def build(summary, prefix, out):
    groups = []  # [(title, href, [(title, href)])]
    for line in open(os.path.join(ROOT, summary), encoding="utf-8"):
        m = ITEM.match(line)
        if not m:
            continue
        indent, title, target = m.groups()
        entry = (html.escape(title), url(prefix, target))
        if indent:
            groups[-1][2].append(entry)
        else:
            groups.append((*entry, []))
    parts = ["<!-- generated by scripts/build-nav.py from %s; do not edit -->\n<ul>" % summary]
    for title, href, children in groups:
        parts.append(f'<li class="grp"><a href="{href}">{title}</a>')
        if children:
            parts.append("<ul>" + "".join(f'<li><a href="{h}">{t}</a></li>' for t, h in children) + "</ul>")
        parts.append("</li>")
    parts.append("</ul>\n")
    with open(os.path.join(ROOT, "_includes", out), "w", encoding="utf-8") as f:
        f.write("".join(parts))


build("SUMMARY.md", "/", "nav-zh.html")
build("en/SUMMARY.md", "/en/", "nav-en.html")
print("nav built")
